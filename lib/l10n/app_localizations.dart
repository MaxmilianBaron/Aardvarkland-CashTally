  String tr(String key, [Map<String, Object?> values = const {}]) {
    if (key == 'appTitle') {
      return AppTitles.forLanguage(locale.languageCode);
    }
    if (key == 'lifetimeBenefitAllFeaturesBody') {
      return _localizedBenefitBody[locale.languageCode] ??
          _featureEnglishTranslations[key]!;
    }
    var result =
        MonetizationLocalizations.all[locale.languageCode]?[key] ??
        DashboardLocalizations.all[locale.languageCode]?[key] ??
        (_translations[locale.languageCode] ?? _translations['en'])![key] ??
        CompleteLocalizations.all[locale.languageCode]?[key] ??
        _featureTranslations[locale.languageCode]?[key] ??
        MonetizationLocalizations.all['en']?[key] ??
        DashboardLocalizations.all['en']?[key] ??
        _translations['en']![key] ??
        key;
    for (final entry in values.entries) {
      result = result.replaceAll('{${entry.key}}', '${entry.value}');
    }
    return result;
  }

  @visibleForTesting
  static Set<String> missingTranslationKeys(
    String languageCode,
  ) => _translations['en']!.keys.toSet().difference(<String>{
    ...(_translations[languageCode] ?? const <String, String>{}).keys,
    ...(_featureTranslations[languageCode] ?? const <String, String>{}).keys,
  });

  /// Every user-facing key in the English source catalog.
  ///
  /// Kept public so the standalone localization audit can verify the exact
  /// same runtime lookup path as the application instead of parsing Dart
  /// source text.
  static Set<String> get translationKeys => Set<String>.unmodifiable(<String>{
    ..._translations['en']!.keys,
    ...MonetizationLocalizations.all['en']!.keys,
    ..._featureEnglishTranslations.keys,
  });

  /// Keys which still fall back to English for [languageCode] at runtime.
  static Set<String> englishFallbackKeys(
    String languageCode,
  ) => translationKeys.difference(<String>{
    ...(_translations[languageCode] ?? const <String, String>{}).keys,
    ...(MonetizationLocalizations.all[languageCode] ?? const <String, String>{})
        .keys,
    ...(DashboardLocalizations.all[languageCode] ?? const <String, String>{})
        .keys,
    ...(CompleteLocalizations.all[languageCode] ?? const <String, String>{})
        .keys,
    ...(_featureTranslations[languageCode] ?? const <String, String>{}).keys,
  });

  /// Strings authored for [languageCode], excluding English runtime fallbacks.
  ///
  /// This is used by the reproducible grammar audit so an untranslated English
  /// sentence is not incorrectly checked as if it belonged to another
